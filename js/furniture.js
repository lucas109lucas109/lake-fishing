// 가구 한 개를 3D 모형으로 만들어요 (같은 재질끼리 미리 하나로 합쳐서 가벼워요)
export function buildFurniture(THREE, id, glowMat) {
  const f = findFurniture(id);
  const g = new THREE.Group();
  if (!f) return g;
  const parts = { solid: [], glow: [] };
  const box = new THREE.BoxGeometry(1, 1, 1);
  const m4 = new THREE.Matrix4(), q = new THREE.Quaternion(), e = new THREE.Euler();
  const push = (list) => (w, h, d, c, x, y, z, rx = 0, ry = 0, rz = 0) => {
    const geo = box.clone();
    e.set(rx, ry, rz); q.setFromEuler(e);
    m4.compose(new THREE.Vector3(x, y, z), q, new THREE.Vector3(w, h, d));
    geo.applyMatrix4(m4);
    const col = new THREE.Color(c), n = geo.attributes.position.count, arr = new Float32Array(n * 3);
    for (let i = 0; i < n; i++) { arr[i * 3] = col.r; arr[i * 3 + 1] = col.g; arr[i * 3 + 2] = col.b; }
    geo.setAttribute('color', new THREE.BufferAttribute(arr, 3));
    geo.deleteAttribute('uv');
    list.push(geo);
  };
  f.build(push(parts.solid), push(parts.glow), f.opts || {});
  if (parts.solid.length) {
    const mesh = new THREE.Mesh(mergeGeometries(parts.solid, false), new THREE.MeshStandardMaterial({ vertexColors: true, roughness: 0.75 }));
    mesh.castShadow = !f.flat; mesh.receiveShadow = true;
    g.add(mesh);
  }
  if (parts.glow.length) {
    const mesh = new THREE.Mesh(mergeGeometries(parts.glow, false), glowMat || new THREE.MeshBasicMaterial({ vertexColors: true })); // 빛나는 블록은 제 색 그대로 환하게
    g.add(mesh);
  }
  parts.solid.forEach((x) => x.dispose()); parts.glow.forEach((x) => x.dispose());
  try { fixCoplanar(THREE, g, { all: true, quiet: true }); } catch (_) {} // 같은 높이에 겹친 블록 면이 지글거리지 않게 (zfix.js)
  g.userData.dynamic = true; // 옮기고 지울 수 있게 (합치기 최적화에서 빼요)
  return g;
}
